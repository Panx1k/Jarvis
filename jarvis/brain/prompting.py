ACTIONS_NOTE_RE = re.compile(r"\s*\[(?:выполненные действия|executed actions)[^\]]*\]", re.I)


def history_pairs(rt, limit: int = 6) -> list[tuple[str, str]]:
    """Последние ходы диалога (пользователь, ассистент). Выполненные действия в текст ответов НЕ вписываем:
    модели начинают копировать такие пометки в свои ответы вместо настоящих вызовов инструментов —
    действия передаются отдельно в контексте хода (turn_prompt)."""
    out = []
    for turn in list(rt.dialog.history)[-limit:]:
        if turn.user and turn.reply:
            out.append((turn.user, ACTIONS_NOTE_RE.sub("", turn.reply)))
    return out


def recent_actions(rt, limit: int = 3) -> str:
    items = [f"«{t.user}» → {', '.join(t.actions)}" for t in list(rt.dialog.history)[-limit:] if t.actions]
    return "; ".join(items)


def turn_prompt(rt, text: str) -> str:
    """Реплика пользователя вместе с текущим состоянием (активный сайт, результаты поиска, недавние действия)."""
    now = dt.datetime.now().strftime("%d.%m.%Y %H:%M")
    actions = recent_actions(rt)
    extra = f"\nНедавно вызванные инструменты: {actions}" if actions else ""
    from jarvis.core.knowledge import summary

    known = summary()
    if known:
        extra += f"\nНа компьютере: {known}"
    hint = getattr(rt, "speech_hint", None)
    speech = (f"\n\n[Распознавание речи] {hint}. Если распознанная фраза выглядит ошибкой распознавания, пойми "
              f"смысл по вариантам и контексту; если смысл всё равно неясен — коротко переспроси, а не выполняй "
              f"случайное действие.") if hint else ""
    return f"[Контекст на {now}]\n{rt.dialog.snapshot()}{extra}{speech}\n\n[Пользователь сказал]\n{text}"


_CJK_RE = re.compile(r"[　-〿぀-ヿ㐀-䶿一-鿿＀-￯]+")


def clean_reply(text: str) -> str:
    """Убрать из ответа модели служебные пометки и случайные иероглифы (особенность небольших моделей Qwen)."""
    text = ACTIONS_NOTE_RE.sub("", text or "")
    text = _CJK_RE.sub(" ", text)
    return re.sub(r"\s+([,.!?])", r"\1", re.sub(r"\s{2,}", " ", text)).strip()
